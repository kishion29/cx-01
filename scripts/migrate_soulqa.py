# 渲染模拟（与将写入 JS 的 qTxt 逻辑保持一致）
# ============================================================
MODE_LIST = [('sync', '我们的答案'), ('meGuess', '我猜TA'), ('taGuess', 'TA猜我')]

def render(tpl, mode):
    t = tpl
    if '{猜者}' in t or '{对方}' in t:
        gu = {'sync': ('你','TA'), 'meGuess': ('TA','你'), 'taGuess': ('你','TA')}[mode]
        # 0: 猜者  1: 对方
        m = {}
        m['猜者'], m['对方'] = gu
        m['对象'] = {'sync': '你', 'meGuess': 'TA', 'taGuess': '你'}[mode]
        m['我们'] = '我们' if m['猜者'] == '你' else '你们'
        m['你'], m['TA'] = '你', 'TA'
        for k in ['猜者','对方','对象','我们','你','TA']:
            t = t.replace('{'+k+'}', m[k])
        return t
    if '{对象}' in t or '{我们}' in t:
        pre = ''
        if not (t.startswith('你觉得') or t.startswith('TA觉得')):
            if mode == 'meGuess':
                pre = '你觉得'
            elif mode == 'taGuess':
                pre = 'TA觉得'
        m = {}
        m['对象'] = {'sync': '你', 'meGuess': 'TA', 'taGuess': '你'}[mode]
        m['我们'] = {'sync': '我们', 'meGuess': '你们', 'taGuess': '你们'}[mode]
        m['你'], m['TA'] = '你', 'TA'
        for k in ['对象','我们','你','TA']:
            t = t.replace('{'+k+'}', m[k])
        return pre + t
    if '{你}' in t or '{TA}' in t:
        return t.replace('{你}', '你').replace('{TA}', 'TA')
    return t

