def main():
    src_path = os.path.abspath(SRC)
    if not os.path.exists(src_path):
        print('找不到 28_misc.js:', src_path)
        sys.exit(1)
    with io.open(src_path, 'r', encoding='utf-8') as f:
        content = f.read()

    # 备份
    bak = src_path + '.bak_soulqa'
    if not os.path.exists(bak):
        with io.open(bak, 'w', encoding='utf-8') as f:
            f.write(content)
        print('已备份 ->', os.path.basename(bak))
    else:
        print('备份已存在（跳过）:', os.path.basename(bak))

    # 替换 PRESETS 块
    pat = re.compile(r'  var PRESETS=\[.*?\n  \];\n  // 模式说明', re.S)
    new_presets = gen_presets()
    new_content, n = pat.subn(new_presets + '\n  // 模式说明', content)
    if n != 1:
        print('!! PRESETS 块匹配失败，替换未执行 (n=%d)' % n)
        sys.exit(1)
    with io.open(src_path, 'w', encoding='utf-8') as f:
        f.write(new_content)
    print('已替换 PRESETS 块（27 套题库）')

    # 渲染验证
    out = []
    total_q = 0
    errs = []
    for qz in DATA:
        out.append('')
        out.append('===== %s %s（%s）%d 题 =====' % (qz['id'], qz['name'], qz['group'], len(qz['questions'])))
        for i, (q, opts) in enumerate(qz['questions']):
            total_q += 1
            row = ['  第%02d题  模板: %s' % (i + 1, q)]
            for mk, mn in MODE_LIST:
                r = render(q, mk)
                if '{' in r or '}' in r:
                    errs.append('[残留占位符] %s %s 第%d题 %s -> %s' % (qz['id'], mn, i + 1, q, r))
                for bad in ('你觉得你觉得', 'TA觉得TA觉得', '你觉得TA觉得', 'TA觉得你觉得'):
                    if bad in r:
                        errs.append('[病句] %s %s 第%d题 %s -> %s' % (qz['id'], mn, i + 1, q, r))
                row.append('    · %s → %s' % (mn, r))
            out.append('\n'.join(row))
    with io.open(CHECK_OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))
    print('渲染清单已输出 ->', os.path.basename(CHECK_OUT), '（共 %d 题 × 3 模式）' % total_q)
    if errs:
        print('\n!! 发现问题 %d 处：' % len(errs))
        for e in errs:
            print('  ', e)
    else:
        print('✓ 验证通过：无残留占位符、无病句')

if __name__ == '__main__':
    main()
